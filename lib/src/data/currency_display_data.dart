/// Display metadata for one circulating currency.
class CurrencyDisplayData {
  const CurrencyDisplayData(
    this.name,
    this.symbol,
    this.countryCode, {
    this.isIso4217 = true,
    this.decimalDigits,
    this.symbolFontFamily,
  });

  final String name;
  final String symbol;

  /// Representative flag region; empty when no Unicode region flag exists.
  final String countryCode;

  /// False for currencies assigned a local identifier by this package.
  final bool isIso4217;

  /// Decimal convention for local currencies that `intl` does not know.
  final int? decimalDigits;

  /// Bundled font required to render a package-specific currency symbol.
  final String? symbolFontFamily;
}

